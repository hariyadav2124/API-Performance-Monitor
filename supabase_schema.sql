-- 1. Create endpoints table
CREATE TABLE IF NOT EXISTS public.endpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    interval INTEGER NOT NULL DEFAULT 60,
    threshold INTEGER NOT NULL DEFAULT 500,
    expected_status INTEGER,
    next_due DOUBLE PRECISION NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 0
);

-- 2. Create checks table
CREATE TABLE IF NOT EXISTS public.checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id BIGINT NOT NULL REFERENCES public.endpoints(id) ON DELETE CASCADE,
    ts DOUBLE PRECISION NOT NULL,
    latency DOUBLE PRECISION NOT NULL,
    status INTEGER,
    ok INTEGER NOT NULL,
    error TEXT,
    source TEXT NOT NULL
);

-- 3. Indexes for fast query and chart loading
CREATE INDEX IF NOT EXISTS checks_endpoint_ts ON public.checks(endpoint_id, ts DESC);
CREATE INDEX IF NOT EXISTS checks_ts ON public.checks(ts DESC);

-- 4. Enable RLS and allow full access for anon (publishable key) & service_role
ALTER TABLE public.endpoints ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.checks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all for endpoints" ON public.endpoints;
CREATE POLICY "Allow all for endpoints" ON public.endpoints FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all for checks" ON public.checks;
CREATE POLICY "Allow all for checks" ON public.checks FOR ALL USING (true) WITH CHECK (true);

-- 5. Grant permissions to anon, authenticated and service_role
GRANT ALL ON public.endpoints TO anon, authenticated, service_role;
GRANT ALL ON public.checks TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
